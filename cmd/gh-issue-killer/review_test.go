func TestReviewInstructions(t *testing.T) {
	gh, _ := newFakeAPI(t, func(w http.ResponseWriter, r *http.Request) {
		switch {
		case strings.HasSuffix(r.URL.Path, "/pulls/5/reviews/9"):
			_ = json.NewEncoder(w).Encode(map[string]any{
				"id":   9,
				"user": map[string]string{"login": "bot"},
				"body": "### 🤖 Review\n\nneeds a timeout\n\n**Verdict:** ⚠️ request changes\n\n🤖 Generated by [gh-issue-killer](x)",
			})
		case strings.HasSuffix(r.URL.Path, "/pulls/5/comments"):
			_ = json.NewEncoder(w).Encode([]map[string]any{
				{"id": 1, "path": "a.py", "line": 4, "body": "blocks forever", "pull_request_review_id": 9},
				{"id": 2, "path": "b.py", "line": 8, "body": "from another review", "pull_request_review_id": 8},
			})
		default:
			w.WriteHeader(http.StatusNotFound)
		}
	})
	app := &AppContext{Repo: RepoConfig{FullName: "acme/app"}, GH: gh, Log: NewSilentLogger(), AgentLogin: "bot"}
	pr := PullRequest{Number: 5}

	got, err := reviewInstructions(context.Background(), app, pr, 9)
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{"needs a timeout", "a.py:4", "blocks forever"} {
		if !strings.Contains(got, want) {
			t.Fatalf("instructions missing %q:\n%s", want, got)
		}
	}
	for _, unwanted := range []string{"### 🤖 Review", "**Verdict:**", "from another review", "🤖 Generated by"} {
		if strings.Contains(got, unwanted) {
			t.Fatalf("instructions contain %q:\n%s", unwanted, got)
		}
	}
}

