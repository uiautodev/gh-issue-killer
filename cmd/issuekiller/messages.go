// language is the concrete scaffolding language for a task: an explicit
// config.language wins, otherwise the issue/PR text decides.
func (app *AppContext) language(number int) string {
	configured := strings.TrimSpace(app.Repo.Language)
	if configured == "" && app.Cfg != nil {
		configured = strings.TrimSpace(app.Cfg.Language)
	}
	if configured != "" && !strings.EqualFold(configured, "auto") {
		if strings.HasPrefix(strings.ToLower(configured), "zh") {
			return "zh"
		}
		return "en"
	}
	sample := ""
	if app.Store != nil {
		st := app.Store.Issue(app.Repo.FullName, number)
		if st.Issue != nil {
			sample = st.Issue.Title + "\n" + st.Issue.Body
		}
		if sample == "" {
			sample = st.Plan
		}
	}
	return detectLanguage(sample)
}

// text returns a scaffolding string in the task's language, formatted with args.
func (app *AppContext) text(number int, key string, args ...any) string {
	return scaffoldText(app.language(number), key, args...)
}

func scaffoldText(lang, key string, args ...any) string {
	set := scaffoldEN
	if lang == "zh" {
		set = scaffoldZH
	}
	format, ok := set[key]
	if !ok {
		format = scaffoldEN[key]
	}
	if format == "" {
		return key
	}
	if len(args) == 0 {
		return format
	}
	return fmt.Sprintf(format, args...)
}

// detectLanguage picks the scaffolding language for a text sample. Only zh and
// en have catalogs; everything else (kana, hangul, Latin) falls back to English.
func detectLanguage(sample string) string {
	var han, latin, kana, hangul int
	for _, r := range sample {
		switch {
		case unicode.Is(unicode.Hiragana, r) || unicode.Is(unicode.Katakana, r):
			kana++
		case unicode.Is(unicode.Hangul, r):
			hangul++
		case unicode.Is(unicode.Han, r):
			han++
		case unicode.Is(unicode.Latin, r):
			latin++
		}
	}
	if kana > 0 || hangul > 0 {
		return "en"
	}
	if han >= 4 && han*3 >= latin {
		return "zh"
	}
	return "en"
}
