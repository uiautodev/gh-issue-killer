const TABLES: Record<Lang, Record<string, string>> = { zh, en };

export const i18n = $state<{ lang: Lang }>({ lang: 'zh' });

export function t(key: string, vars?: Record<string, string | number>): string {
	const table = TABLES[i18n.lang] || zh;
	let out = table[key];
	if (out === undefined) out = zh[key] !== undefined ? zh[key] : key;
	if (vars) {
		for (const [name, value] of Object.entries(vars)) {
			out = out.split('{' + name + '}').join(String(value));
		}
	}
	return out;
}

export function storedLang(): Lang {
	try {
		return localStorage.getItem(LANG_KEY) === 'en' ? 'en' : 'zh';
	} catch {
		return 'zh';
	}
}

export function applyLanguage(lang: Lang): void {
	i18n.lang = lang === 'en' ? 'en' : 'zh';
	try {
		localStorage.setItem(LANG_KEY, i18n.lang);
	} catch {
		/* private mode */
	}
	document.documentElement.lang = i18n.lang === 'zh' ? 'zh-CN' : 'en';
	document.title = t('document.title');
}
